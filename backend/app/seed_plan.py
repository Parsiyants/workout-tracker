def _relative(url: str) -> str:
    """Абсолютные ссылки на storage → относительные (работает и с телефона).

    Срезаем любой scheme://host[:port], оставляя только путь (/files/...).
    """
    match = re.match(r"^https?://[^/]+", url)
    if match:
        rest = url[match.end() :]
        return rest if rest.startswith("/") else f"/{rest}"
    return url


async def normalize_media(db: AsyncSession) -> None:
    """Одноразово переводит старые абсолютные ссылки storage в относительные."""
    exercises = list(await db.scalars(select(Exercise)))
    for exercise in exercises:
        media = exercise.media or []
        normalized = [
            {**item, "url": _relative(item["url"])} if item.get("url") else item for item in media
        ]
        if normalized != media:
            exercise.media = normalized

    categories = list(await db.scalars(select(Category)))
    for category in categories:
        if category.image_url:
            category.image_url = _relative(category.image_url)


async def _ensure_exercises(db: AsyncSession) -> dict[str, Exercise]:
    categories = {category.slug: category for category in await db.scalars(select(Category))}
    by_name = {exercise.name: exercise for exercise in await db.scalars(select(Exercise))}

    for name, slug, metric_type, description in EXERCISES:
        if name in by_name:
            continue
        category = categories.get(slug)
        if category is None:
            continue
        exercise = Exercise(
            name=name,
            description=description,
            category_id=category.id,
            metric_type=metric_type,
            media=[],
        )
        db.add(exercise)
        by_name[name] = exercise

    await db.flush()
    return by_name


async def _ensure_templates(db: AsyncSession, user: User, by_name: dict[str, Exercise]) -> None:
    existing = set(
        await db.scalars(select(WorkoutTemplate.name).where(WorkoutTemplate.user_id == user.id))
    )
    last_order = await db.scalar(
        select(func.max(WorkoutTemplate.order_index)).where(WorkoutTemplate.user_id == user.id)
    )
    order = last_order or 0

    for name, items in TEMPLATES:
        if name in existing:
            continue
        exercises: list[dict[str, object]] = []
        for exercise_name, sets, reps, duration in items:
            exercise = by_name.get(exercise_name)
            if exercise is None:
                continue
            exercises.append(
                {
                    "exercise_id": exercise.id,
                    "target_sets": sets,
                    "target_reps": reps,
                    "target_duration_sec": duration,
                    "target_weight": None,
                }
            )
        if not exercises:
            continue

        order += 1
        db.add(
            WorkoutTemplate(
                user_id=user.id,
                name=name,
                order_index=order,
                exercises=exercises,
            )
        )


async def seed_plan(db: AsyncSession, admin: User) -> None:
    await normalize_media(db)
    by_name = await _ensure_exercises(db)
    await _ensure_templates(db, admin, by_name)
